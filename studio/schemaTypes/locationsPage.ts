import {defineArrayMember, defineField, defineType} from 'sanity'
import {cityPageContent, locationServices, locationsPageContent} from '../../data/locations'

// The one Locations page document: text on the Locations page itself, plus
// what every city page shares. The page header lives in Page header.
export const locationsPage = defineType({
  name: 'locationsPage',
  title: 'Locations page',
  type: 'document',
  groups: [
    {name: 'main', title: 'Main page', default: true},
    {name: 'cityPages', title: 'Every city page'},
  ],
  initialValue: {
    eyebrow: locationsPageContent.eyebrow,
    citiesHeading: locationsPageContent.citiesHeading,
    citiesDescription: locationsPageContent.citiesDescription,
    nextHeading: locationsPageContent.nextHeading,
    nextText: locationsPageContent.nextText,
    servicesLabel: locationsPageContent.servicesLabel,
    photoEyebrow: cityPageContent.photoEyebrow,
    photoHeading: cityPageContent.photoHeading,
    quoteLabel: cityPageContent.quoteLabel,
    servicesDescription: cityPageContent.servicesDescription,
    servicesLinkLabel: cityPageContent.servicesLinkLabel,
    backLabel: cityPageContent.backLabel,
    services: locationServices.map((service, index) => ({
      _key: `service-${index}`,
      _type: 'locationService',
      ...service,
    })),
  },
  fields: [
    defineField({
      name: 'eyebrow',
      title: 'Small heading',
      type: 'string',
      group: 'main',
      description: 'The gold line above the page title. The title and intro are in Page header.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'citiesHeading',
      title: 'City list heading',
      type: 'string',
      group: 'main',
      description: 'Above the list of city links, under the map.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'citiesDescription',
      title: 'City list text',
      type: 'string',
      group: 'main',
      description: 'One line under the city list heading.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'nextHeading',
      title: 'Bottom panel heading',
      type: 'string',
      group: 'main',
      description: 'The dark panel at the bottom of the page that leads to Services.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'nextText',
      title: 'Bottom panel text',
      type: 'text',
      rows: 2,
      group: 'main',
      description: 'One or two sentences under the bottom panel heading.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'servicesLabel',
      title: 'Bottom panel button',
      type: 'string',
      group: 'main',
      description: 'The button that opens the Services page.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'media',
      title: 'Shared photo or video',
      type: 'photoOrVideo',
      group: 'cityPages',
      description:
        'Used on every city page that doesn’t have its own. Leave it empty to keep the photo the city pages use today.',
    }),
    defineField({
      name: 'photoEyebrow',
      title: 'Photo section small heading',
      type: 'string',
      group: 'cityPages',
      description: 'The small line above the heading next to the photo.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'photoHeading',
      title: 'Photo section heading',
      type: 'text',
      rows: 2,
      group: 'cityPages',
      description: 'Press Enter where you want the heading to start a new line.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'quoteLabel',
      title: 'Quote button text',
      type: 'string',
      group: 'cityPages',
      description: 'The button under the city description.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'servicesDescription',
      title: 'Services intro',
      type: 'string',
      group: 'cityPages',
      description: 'One line under “Services in [city]”.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'servicesLinkLabel',
      title: 'Services link text',
      type: 'string',
      group: 'cityPages',
      description: 'The link to the full Services page.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'backLabel',
      title: 'Back link text',
      type: 'string',
      group: 'cityPages',
      description: 'The link at the top of every city page that returns to the Locations page.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'services',
      title: 'Service summaries',
      type: 'array',
      group: 'cityPages',
      description: 'The boxes under “Services in [city]”. Drag to reorder, click one to edit it.',
      of: [
        defineArrayMember({
          name: 'locationService',
          title: 'Service',
          type: 'object',
          fields: [
            defineField({
              name: 'name',
              title: 'Service name',
              type: 'string',
              validation: (rule) => rule.required(),
            }),
            defineField({
              name: 'description',
              title: 'Short description',
              type: 'string',
              validation: (rule) => rule.required(),
            }),
          ],
          preview: {select: {title: 'name', subtitle: 'description'}},
        }),
      ],
      validation: (rule) => rule.min(1).error('Add at least one service.'),
    }),
  ],
  preview: {
    prepare: () => ({title: 'Locations page'}),
  },
})
